#!/usr/bin/env python3
"""Generate one API route per main-menu feature, per system.

Each system's GUI and CLI present the same navigation; this mirrors that
navigation onto the API so every feature a user can reach in the desktop app
has an addressable endpoint. Routes land under a dedicated ``/menu`` segment
so they can never collide with the hand-written resource routes that already
exist — those remain the real implementation where they exist.

Re-runnable: the menus are the source of truth, so regenerate after a menu
changes rather than editing the output. A handler whose body has been
replaced with a real implementation is kept as it is (matched by its route);
if its menu entry is gone the run stops instead of deleting it.
"""

from __future__ import annotations

import ast
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src"))

from education_system.systems.menu_inventory import (  # noqa: E402
    all_menus,
    slugify,
    snake,
)

ROOT = pathlib.Path(__file__).resolve().parents[1] / "src/education_system/api"

HEADER = '''"""{category} routes for the {title} system.

Generated by ``tools/gen_menu_routes.py`` from the {system} main menu, so the
API offers an endpoint for every feature the GUI and CLI present. Do not edit
by hand — change the menu and regenerate.

Each handler answers 501 until it is backed by a service. Replace a body with
a real implementation and delete its entry from
``tests/contract/platform/menu_backlog.json``.
"""

from __future__ import annotations

from flask import Blueprint

from education_system.platform.delivery.api.kernel.pending import feature_pending
from education_system.platform.delivery.api.security.decorators import (
    staff_required,
    token_required,
)

{var} = Blueprint("{bp_name}", __name__, url_prefix="/api/menu/{cat_slug}")

_SYSTEM = "{system}"
_CATEGORY = "{category}"

'''

HANDLER = '''
@{var}.route("/{slug}", methods=["GET"])
@token_required
@staff_required
def {fn}():
    """{feature}"""
    return feature_pending("{feature}", _SYSTEM, category=_CATEGORY)

'''


def _implemented(path: pathlib.Path) -> dict[str, str]:
    """Hand-written handlers in an existing file, by route slug -> source
    (decorators included). A generated handler only returns feature_pending."""
    if not path.exists():
        return {}
    src = path.read_text(encoding="utf-8")
    lines = src.splitlines(keepends=True)
    out: dict[str, str] = {}
    for node in ast.parse(src).body:
        if not isinstance(node, ast.FunctionDef) or not node.decorator_list:
            continue
        body = [b for b in node.body
                if not (isinstance(b, ast.Expr) and isinstance(b.value, ast.Constant))]
        call = body[0].value if len(body) == 1 and isinstance(body[0], ast.Return) else None
        if isinstance(call, ast.Call) and getattr(call.func, "id", "") == "feature_pending":
            continue
        route = next((d for d in node.decorator_list if isinstance(d, ast.Call)
                      and getattr(d.func, "attr", "") == "route"), None)
        if route is None or not route.args or not isinstance(route.args[0], ast.Constant):
            continue
        start = min(d.lineno for d in node.decorator_list)
        out[str(route.args[0].value).lstrip("/")] = "".join(lines[start - 1:node.end_lineno])
    return out


def generate(only: set[str] | None = None) -> dict[str, int]:
    """Write the menu routes for every system, or just those in *only*."""
    counts: dict[str, int] = {}
    for system, menu in all_menus().items():
        if only and system not in only:
            continue
        package = ROOT / system / "routes" / "menu"
        package.mkdir(parents=True, exist_ok=True)
        modules: list[tuple[str, str]] = []
        made = 0
        for category, features in sorted(menu.items()):
            cat_slug = slugify(category)
            cat_snake = snake(category)
            var = f"{cat_snake}_menu_bp"
            bp_name = f"{system}_menu_{cat_snake}"
            text = HEADER.format(category=category, title=system.replace("_", " ").title(),
                                 system=system, var=var, bp_name=bp_name,
                                 cat_slug=cat_slug)
            target = package / f"{cat_snake}_routes.py"
            kept = _implemented(target)
            seen: set[str] = set()
            for feature in features:
                fn = f"{cat_snake}_{snake(feature)}"[:60]
                if fn in seen:
                    continue
                seen.add(fn)
                slug = slugify(feature)
                if slug in kept:
                    text += "\n" + kept.pop(slug) + "\n"
                else:
                    text += HANDLER.format(var=var, slug=slug, fn=fn,
                                           feature=feature.replace('"', "'"))
                made += 1
            if kept:
                raise SystemExit(f"{target}: implemented handler(s) for /{', /'.join(kept)} "
                                 "have no menu entry any more - move or delete them by hand")
            target.write_text(text, encoding="utf-8")
            modules.append((f"{cat_snake}_routes", var))

        imports = "\n".join(
            f"from education_system.api.{system}.routes.menu.{mod} import {var}"
            for mod, var in modules)
        listed = "\n".join(f"    {var}," for _mod, var in modules)
        (package / "__init__.py").write_text(
            f'''"""Main-menu feature routes for the {system} system.

Generated by ``tools/gen_menu_routes.py``. ``MENU_BLUEPRINTS`` is collected by
the system's route package.
"""

{imports}

MENU_BLUEPRINTS = [
{listed}
]

__all__ = ["MENU_BLUEPRINTS"]
''', encoding="utf-8")
        counts[system] = made
    return counts


if __name__ == "__main__":
    # Optional system keys limit the run: python tools/gen_menu_routes.py secondary
    for system, n in generate(set(sys.argv[1:]) or None).items():
        print(f"  {system:16} {n:3} menu routes")
