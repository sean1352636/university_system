"""Export a census / ILR return to CSV and to ILR-style XML.

Four outputs:

* :func:`export_ilr_csv` — **the ILR file**: one ``Learner`` row and one
  ``LearningDelivery`` row per aim for every learner in a funding year,
  with the problems that need fixing. It is the only ILR export: the
  Census ILR screens and the Enrolment screens (``enrolments.ilr.export_csv``
  delegates here) both produce it, from the rows the return builder takes
  from the per-enrolment ILR records and aim outcomes. It is open to
  funding, admissions or students.manage and logged as sensitive access.

* :func:`to_csv` — every aim with its learner's fields, one row per aim.
  A working file for checking the return in a spreadsheet.
* :func:`to_census_aims_csv` — for a sixth form **in a school**: the
  post-16 learning aims module of the school census, one row per aim
  (ULN / UPN, QAN, dates, completion status, withdrawal reason, planned
  learning hours, planned employability / enrichment / pastoral hours).
* :func:`to_ilr_xml` — for a **college**: an ILR-style XML file with a
  ``Header``, ``LearningProvider`` and one ``Learner`` per learner, each
  holding its ``LearningDelivery`` elements.

**Check before submitting.** The column set, element names, code values
(ethnicity, LLDD, AimType, FundModel, CompStatus, WithdrawReason,
Outcome) and the XML namespace follow the published shape of the ILR
and the school census as the college understood it, and they change
every year. The file MUST be checked against the current ESFA ILR
specification (and its XSD) or the DfE school census guidance, and run
through FIS / COLLECT, before it is submitted. Nothing here submits.

Export refuses a return with validation errors unless ``allow_errors``
is passed (then the file is marked DRAFT).
"""

from __future__ import annotations

import csv
import datetime as _dt
import io
import logging
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

from education_system.systems.sixth_form.domains.finance.domain.census_ilr import (
    census_ilr as core,
    return_builder as builder,
    return_validation as validation,
)

logger = logging.getLogger(__name__)

ValidationError = core.ValidationError

SPEC_NOTICE = (
    "Generated by the Sixth Form system. Check against the current ESFA "
    "ILR specification / DfE school census guidance and validate in "
    "FIS / COLLECT before submission.")

# ILR code lists used in the XML (check against the current spec).
_FUND_MODEL = {"16-19 (excluding Apprenticeships)": "25",
               "Apprenticeship": "36", "Adult Skills": "35",
               "Advanced Learner Loans": "99", "Community Learning": "10",
               "ESFA Other": "70", "Other": "99"}
# AimType: 5 = core aim of a 16-19 study programme, 4 = other aims.
_AIM_TYPE = {"Core Aim": "5"}
# census_ilr completion code -> (ILR CompStatus, WithdrawReason)
_COMP_STATUS = {1: ("1", None), 2: ("2", None), 3: ("3", None),
                6: ("6", None), 7: ("3", "41"), 10: ("2", None)}
# ILR LLDDHealthProb: 1 has a difficulty / disability (an open SEND
# register entry); 9 not provided — no entry is not a declaration of "no".
LLDD_YES, LLDD_NOT_PROVIDED = "1", "9"


def _lldd(flag) -> str:
    return LLDD_YES if flag else LLDD_NOT_PROVIDED


def _comp_withdraw(a: core.LearnerAim) -> tuple[str | None, str | None]:
    """(ILR CompStatus, WithdrawReason) for an aim: the reason code
    recorded on the enrolment wins over the one implied by a transfer."""
    comp, withdraw = _COMP_STATUS.get(a.completion_code or 0, (None, None))
    if comp == "3":
        withdraw = a.withdraw_reason_code or withdraw
    return comp, withdraw


def _ensure_ok(return_id: int, allow_errors: bool) -> bool:
    """Run validation; raise if errors and not allowed. True = draft."""
    findings = validation.run(return_id)
    errors = [f for f in findings if f.severity == validation.ERROR]
    if errors and not allow_errors:
        raise ValidationError(
            f"{len(errors)} validation error(s) must be fixed before this "
            "return can be exported (or export it as a draft)")
    return bool(errors)


def _rows(return_id: int):
    learners = {ln.learner_ref: ln for ln in builder.list_learners(return_id)}
    aims = core.aims_for_return(return_id)
    return learners, aims


# ── Working CSV ────────────────────────────────────────────────────

CSV_COLUMNS: tuple[str, ...] = (
    "learner_ref", "uln", "family_name", "given_names", "date_of_birth",
    "sex", "postcode", "ethnicity", "lldd", "ehcp", "age_31_aug",
    "prior_attainment", "gcse_english", "gcse_maths", "planned_hours",
    "planned_qual_hours", "planned_eep_hours", "funding_band",
    "cof_compliant", "attendance_pct", "aim_id", "source", "aim_type",
    "aim_reference", "aim_title", "qualification_type", "funding_model",
    "start_date", "planned_end_date", "actual_end_date", "status",
    "completion_code", "withdrawal_reason", "outcome_code",
    "outcome_grade", "aim_planned_hours", "qualifying_met", "overrides",
    "enrolment_id", "fee_status", "fund_model", "ffi", "study_mode",
    "early_leaver", "withdraw_reason_code", "outcome_source",
    "achievement_date",
)
_LEARNER_CSV_FIELDS: tuple[str, ...] = (
    "uln", "family_name", "given_names", "date_of_birth", "sex", "postcode",
    "ethnicity", "lldd", "ehcp", "age_31_aug", "prior_attainment",
    "gcse_english", "gcse_maths", "planned_hours", "planned_qual_hours",
    "planned_eep_hours", "funding_band", "cof_compliant", "attendance_pct",
    "enrolment_id", "fee_status", "fund_model", "ffi", "study_mode",
    "early_leaver",
)


def to_csv(return_id: int, *, allow_errors: bool = False) -> str:
    builder._guard("export return CSV")
    _ensure_ok(return_id, allow_errors)
    learners, aims = _rows(return_id)
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(CSV_COLUMNS)
    for a in aims:
        ln = learners.get(a.learner_ref)
        rec = {
            "aim_id": a.aim_id, "source": a.source, "aim_type": a.aim_type,
            "aim_reference": a.aim_reference, "aim_title": a.aim_title,
            "qualification_type": a.qualification_type,
            "funding_model": a.funding_model, "start_date": a.start_date,
            "planned_end_date": a.planned_end_date,
            "actual_end_date": a.actual_end_date, "status": a.status,
            "completion_code": a.completion_code,
            "withdrawal_reason": a.withdrawal_reason,
            "outcome_code": a.outcome_code, "outcome_grade": a.outcome_grade,
            "aim_planned_hours": a.planned_hours,
            "qualifying_met": ("" if a.qualifying_met is None
                               else int(a.qualifying_met)),
            "overrides": " ".join(a.overrides),
            "learner_ref": a.learner_ref, "uln": a.uln,
            "withdraw_reason_code": a.withdraw_reason_code,
            "outcome_source": a.outcome_source,
            "achievement_date": a.achievement_date,
        }
        if ln is not None:
            for k in _LEARNER_CSV_FIELDS:
                rec[k] = getattr(ln, k)
            if ln.overrides:
                rec["overrides"] = (rec["overrides"] + " learner:"
                                    + ",".join(ln.overrides)).strip()
        elif a.learner_name:
            rec["family_name"] = a.learner_name
        w.writerow(["" if rec.get(c) is None else rec.get(c)
                    for c in CSV_COLUMNS])
    return buf.getvalue()


# ── School census: post-16 learning aims module ────────────────────

CENSUS_AIM_COLUMNS: tuple[str, ...] = (
    "ULN", "UPN", "Surname", "Forename", "DOB", "Sex",
    "QAN", "AimTitle", "LearningStartDate", "LearningPlannedEndDate",
    "LearningActualEndDate", "CompletionStatus", "WithdrawalReason",
    "Outcome", "Grade", "PlannedLearningHours", "PlannedEEPHours",
)


def to_census_aims_csv(return_id: int, *, allow_errors: bool = False) -> str:
    """Post-16 learning aims module rows (school census route).

    Planned learning hours are per aim; planned EEP (employability,
    enrichment and pastoral) hours are per learner and are written on
    the learner's first aim only, so they are not double counted.
    """
    builder._guard("export census learning aims")
    _ensure_ok(return_id, allow_errors)
    learners, aims = _rows(return_id)
    upns = _upns([a.student_id for a in aims if a.student_id])
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(CENSUS_AIM_COLUMNS)
    eep_done: set[str] = set()
    for a in aims:
        ln = learners.get(a.learner_ref)
        comp, withdraw = _comp_withdraw(a)
        comp = comp or ""
        eep = ""
        if ln is not None and a.learner_ref not in eep_done:
            eep = "" if ln.planned_eep_hours is None else round(ln.planned_eep_hours)
            eep_done.add(a.learner_ref)
        w.writerow([
            (ln.uln if ln else a.uln) or "",
            upns.get(a.student_id or "", ""),
            (ln.family_name if ln else a.learner_name) or "",
            (ln.given_names if ln else "") or "",
            (ln.date_of_birth if ln else "") or "",
            (ln.sex if ln else "") or "",
            a.aim_reference or "", a.aim_title or "",
            a.start_date or "", a.planned_end_date or "",
            a.actual_end_date or "", comp, withdraw or "",
            a.outcome_code or "", a.outcome_grade or "",
            a.planned_hours if a.planned_hours is not None else "", eep,
        ])
    return buf.getvalue()


def _upns(student_ids: list[str]) -> dict[str, str]:
    """UPNs as the student record holds them (the CTF UPN link table)."""
    try:
        s = builder._students()
        out: dict[str, str] = {}
        for sid in set(student_ids):
            upn = s.get_upn(sid)
            if upn:
                out[sid] = str(upn)
        return out
    except Exception:
        logger.debug("UPN lookup for the return failed", exc_info=True)
        return {}


# ── ILR-style XML ──────────────────────────────────────────────────

def _el(parent: ET.Element, tag: str, value) -> None:
    if value is None or value == "":
        return
    ET.SubElement(parent, tag).text = str(value)


def _ilr_year(academic_year: str) -> str:
    y = int(builder.normalise_year(academic_year)[:4])
    return f"{str(y)[-2:]}{str(y + 1)[-2:]}"


def to_ilr_xml(return_id: int, *, allow_errors: bool = False) -> bytes:
    """ILR-shaped XML: Header, LearningProvider, Learner/LearningDelivery."""
    builder._guard("export ILR XML")
    draft = _ensure_ok(return_id, allow_errors)
    ret = core.get_return(return_id)
    assert ret is not None
    settings = builder.get_settings()
    learners, aims = _rows(return_id)
    year = builder.normalise_year(ret.academic_year)
    ns = f"ESFA/ILR/{year.replace('/', '-')}"
    root = ET.Element("Message", {"xmlns": ns})
    root.append(ET.Comment(" " + SPEC_NOTICE + " "))
    if draft:
        root.append(ET.Comment(" DRAFT - exported with validation errors; "
                               "do not submit "))
    header = ET.SubElement(root, "Header")
    coll = ET.SubElement(header, "CollectionDetails")
    _el(coll, "Collection", "ILR")
    _el(coll, "Year", _ilr_year(year))
    _el(coll, "FilePreparationDate", _dt.date.today().isoformat())
    src = ET.SubElement(header, "Source")
    _el(src, "ProtectiveMarking", "OFFICIAL-SENSITIVE-Personal")
    _el(src, "UKPRN", settings.get("ukprn"))
    _el(src, "SoftwareSupplier", "Education System")
    _el(src, "SoftwarePackage", "Sixth Form")
    _el(src, "DateTime", _dt.datetime.now().isoformat(timespec="seconds"))
    prov = ET.SubElement(root, "LearningProvider")
    _el(prov, "UKPRN", settings.get("ukprn"))

    by_ref: dict[str, list[core.LearnerAim]] = {}
    for a in aims:
        by_ref.setdefault(a.learner_ref, []).append(a)
    refs = list(learners) + [r for r in by_ref if r not in learners]
    for ref in refs:
        ln = learners.get(ref)
        el = ET.SubElement(root, "Learner")
        _el(el, "LearnRefNumber", ref)
        _el(el, "ULN", (ln.uln if ln else None)
            or next((a.uln for a in by_ref.get(ref, []) if a.uln), None)
            or "9999999999")
        if ln:
            _el(el, "FamilyName", ln.family_name)
            _el(el, "GivenNames", ln.given_names)
            _el(el, "DateOfBirth", ln.date_of_birth)
            _el(el, "Ethnicity", ln.ethnicity or "99")
            _el(el, "Sex", ln.sex)
            _el(el, "LLDDHealthProb", _lldd(ln.lldd))
            _el(el, "PostcodePrior", ln.postcode)
            _el(el, "Postcode", ln.postcode)
            if ln.planned_qual_hours is not None:
                _el(el, "PlanLearnHours", round(ln.planned_qual_hours))
            if ln.planned_eep_hours is not None:
                _el(el, "PlanEEPHours", round(ln.planned_eep_hours))
            _el(el, "MathGrade", ln.gcse_maths or "NONE")
            _el(el, "EngGrade", ln.gcse_english or "NONE")
            if ln.ehcp:
                fam = ET.SubElement(el, "LearnerFAM")
                _el(fam, "LearnFAMType", "EHC")
                _el(fam, "LearnFAMCode", "1")
        for seq, a in enumerate(by_ref.get(ref, []), 1):
            d = ET.SubElement(el, "LearningDelivery")
            _el(d, "LearnAimRef", a.aim_reference)
            _el(d, "AimType", _AIM_TYPE.get(a.aim_type, "4"))
            _el(d, "AimSeqNumber", seq)
            _el(d, "LearnStartDate", a.start_date)
            _el(d, "LearnPlanEndDate", a.planned_end_date)
            fund = _FUND_MODEL.get(a.funding_model, "99")
            _el(d, "FundModel", fund)
            _el(d, "DelLocPostCode", a.delivery_location)
            _el(d, "PartnerUKPRN", a.partner_ukprn)
            comp, withdraw = _comp_withdraw(a)
            _el(d, "CompStatus", comp)
            _el(d, "LearnActEndDate", a.actual_end_date)
            _el(d, "WithdrawReason", withdraw)
            _el(d, "Outcome", a.outcome_code)
            _el(d, "AchDate", a.achievement_date)
            _el(d, "OutGrade", a.outcome_grade)
            if fund == "35" and ln is not None and ln.ffi:
                fam = ET.SubElement(d, "LearningDeliveryFAM")
                _el(fam, "LearnDelFAMType", "FFI")
                _el(fam, "LearnDelFAMCode", ln.ffi)
    for ref in refs:
        ln = learners.get(ref)
        if ln is None or not ln.destination_type:
            continue
        dp = ET.SubElement(root, "LearnerDestinationandProgression")
        _el(dp, "LearnRefNumber", ref)
        _el(dp, "ULN", ln.uln or "9999999999")
        out = ET.SubElement(dp, "DPOutcome")
        _el(out, "OutType", ln.destination_type)
        _el(out, "OutCode", ln.destination_code)
        _el(out, "OutStartDate", ln.destination_start)
        _el(out, "OutCollDate", ln.destination_collected)
    ET.indent(root)
    return ET.tostring(root, encoding="utf-8", xml_declaration=True)


# ── The ILR file (one per funding year) ────────────────────────────

ILR_CSV_COLUMNS: tuple[str, ...] = (
    "RecordType", "LearnRefNumber", "ULN", "FamilyName", "GivenNames",
    "DateOfBirth", "Sex", "Ethnicity", "Postcode", "LLDDHealthProb",
    "PlanLearnHours", "PlanEEPHours", "FundModel", "FFI", "FeeStatus",
    "AimSeqNumber", "LearnAimRef", "AimTitle", "LearnStartDate",
    "LearnPlanEndDate", "LearnActEndDate", "CompStatus", "WithdrawReason",
    "Outcome", "OutGrade",
)


@dataclass
class ExportProblem:
    student_id: str
    enrolment_id: int | None
    aim_id: int | None
    field: str
    message: str
    severity: str = validation.ERROR


@dataclass
class ExportResult:
    academic_year: str
    text: str
    learners: int
    deliveries: int
    problems: list[ExportProblem] = field(default_factory=list)
    path: str | None = None


def _hours(v) -> str:
    return "" if v is None else str(int(round(v)))


def render_ilr_csv(learners: list, aims: list[core.LearnerAim]) -> str:
    """Learner + LearningDelivery rows (ILR field names), learners in order."""
    by_ref: dict[str, list[core.LearnerAim]] = {}
    for a in aims:
        by_ref.setdefault(a.learner_ref, []).append(a)
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=ILR_CSV_COLUMNS, extrasaction="ignore")
    w.writeheader()
    for ln in learners:
        ref = ln.learner_ref
        fund = "" if ln.fund_model is None else ln.fund_model
        ffi = ln.ffi or ""
        w.writerow({
            "RecordType": "Learner", "LearnRefNumber": ref,
            "ULN": ln.uln or "", "FamilyName": ln.family_name or "",
            "GivenNames": ln.given_names or "",
            "DateOfBirth": ln.date_of_birth or "", "Sex": ln.sex or "",
            "Ethnicity": ln.ethnicity or "", "Postcode": ln.postcode or "",
            "LLDDHealthProb": _lldd(ln.lldd),
            "PlanLearnHours": _hours(ln.planned_qual_hours),
            "PlanEEPHours": _hours(ln.planned_eep_hours),
            "FundModel": fund, "FFI": ffi, "FeeStatus": ln.fee_status or "",
        })
        for seq, a in enumerate(by_ref.get(ref, []), start=1):
            comp, withdraw = _comp_withdraw(a)
            w.writerow({
                "RecordType": "LearningDelivery", "LearnRefNumber": ref,
                "ULN": ln.uln or "",
                # A learner with an enrolment carries its FundModel (blank
                # until the fee status is settled); one without, the aim's.
                "FundModel": (fund if ln.enrolment_id is not None
                              else _FUND_MODEL.get(a.funding_model, "")),
                "FFI": ffi, "AimSeqNumber": seq,
                "LearnAimRef": a.aim_reference or "",
                "AimTitle": a.aim_title or "",
                "LearnStartDate": a.start_date or "",
                "LearnPlanEndDate": a.planned_end_date or "",
                "LearnActEndDate": a.actual_end_date or "",
                "CompStatus": comp or "", "WithdrawReason": withdraw or "",
                "Outcome": a.outcome_code or "", "OutGrade": a.outcome_grade or "",
                "PlanLearnHours": _hours(a.planned_hours),
            })
    return buf.getvalue()


def export_ilr_csv(academic_year: str, *, path: str | Path | None = None,
                   as_of: str | None = None) -> ExportResult:
    """The ILR file for a funding year — the one code path for it.

    Every learner the return builder finds in the year (a started
    enrolment, else learning aims in the year or on roll), with learning
    delivery from the enrolment's ILR record and aim outcomes. Nothing is
    stored; the validation rules run on the same rows and every finding
    is returned as a problem (never hidden, never blocking). The file is
    written to *path* (the caller's choice) when given.

    Needs funding, admissions or students.manage; logged as sensitive
    access, refused attempts included.
    """
    builder._ilr_export_guard()
    year = builder.normalise_year(academic_year)
    learners, aims, messages = builder._build_year(year, as_of=as_of)
    who = {ln.learner_ref: ln for ln in learners}
    problems: list[ExportProblem] = []
    for f in validation.check_rows(learners, aims):
        ln = who.get(f.learner_ref or "")
        problems.append(ExportProblem(
            student_id=ln.student_id if ln else (f.learner_ref or ""),
            enrolment_id=ln.enrolment_id if ln else None,
            aim_id=f.aim_id,
            field=validation.RULE_FIELDS.get(f.rule, f.rule),
            message=f.message + (f" -> {f.fix}" if f.fix else ""),
            severity=f.severity))
    for m in messages:
        sid, _, msg = m.partition(": ")
        problems.append(ExportProblem(sid, None, None, "Learner", msg))
    result = ExportResult(academic_year=year, text=render_ilr_csv(learners, aims),
                          learners=len(learners), deliveries=len(aims),
                          problems=problems)
    if path is not None:
        target = Path(path)
        target.write_text(result.text, encoding="utf-8", newline="")
        result.path = str(target)
        logger.info("ILR %s exported to %s", year, target)
    return result


# ── Save helpers ───────────────────────────────────────────────────

def save(return_id: int, path: str, *, kind: str = "csv",
         allow_errors: bool = False) -> str:
    """Write one export to *path*. ``kind``: csv, census_aims, xml."""
    if kind == "csv":
        payload: str | bytes = to_csv(return_id, allow_errors=allow_errors)
    elif kind == "census_aims":
        payload = to_census_aims_csv(return_id, allow_errors=allow_errors)
    elif kind == "xml":
        payload = to_ilr_xml(return_id, allow_errors=allow_errors)
    else:
        raise ValidationError("kind must be csv, census_aims or xml")
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(payload, bytes):
        target.write_bytes(payload)
    else:
        target.write_text(payload, encoding="utf-8")
    logger.info("Return #%s exported (%s) to %s", return_id, kind, target)
    return str(target)


def default_kind() -> str:
    """The export that matches the configured route."""
    return ("census_aims" if builder.get_route() == builder.ROUTE_SCHOOL_CENSUS
            else "xml")


