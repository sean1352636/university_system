def escalate_ticket_manual(auth, ticket_id):
    """Manually escalate a ticket"""
    if not auth or not auth.current_user:
        print("You must be logged in to escalate tickets.")
        return

    from education_system.systems.university.domains.student_support.domain.student_support import (
        auth as support_auth,
    )
    if not support_auth.is_case_worker(auth):
        print("You don't have permission to escalate tickets.")
        return

    reason = input("Escalation reason: ").strip()
    if not reason:
        reason = "Manual escalation"

    from education_system.systems.university.domains.student_support.domain.helpdesk.workflows import escalate_ticket
    # The ticket service checks the signed-in person works this ticket.
    escalate_ticket(ticket_id, reason, actor=auth)

def send_satisfaction_survey(ticket_id):
    """Invite the ticket's requester to rate it: an in-app message now and
    the e-mail copy through the university outbox after commit (once per
    ticket — ``student_support.notify``)."""
    from education_system.systems.university.domains.student_support.domain.student_support import (
        notify, store,
    )
    try:
        with store.writing() as conn:
            row = conn.execute("SELECT subject, requester_username, student_id FROM support_tickets "
                               "WHERE ticket_id = ?", (ticket_id,)).fetchone()
            if row is None:
                print(f"Ticket #{ticket_id} not found.")
                return False
            notices = notify.satisfaction_invite(ticket_id, row['subject'],
                                                 row['requester_username'] or row['student_id'])
            delivered = notify.deliver_in_app(conn, notices)
        notify.after_commit(notices)
    except Exception as e:
        print(f"Error sending satisfaction survey: {e}")
        return False
    if delivered:
        print(f"Satisfaction survey sent to {delivered[0].recipient}")
        return True
    print("The requester has no account to send the survey to.")
    return False


_PERIOD_DAYS = {'daily': 1, 'day': 1, 'weekly': 7, 'week': 7, 'monthly': 30, 'month': 30,
                'quarterly': 91, 'quarter': 91, 'yearly': 365, 'year': 365}


def save_report_to_file(report_type, period, auth):
    """Write a Helpdesk ticket summary for ``period`` (daily / weekly /
    monthly / quarterly / yearly, or a number of days) to the reports folder:
    totals by status, priority, category and team over the tickets the
    signed-in staff member may see — counts only, no ticket text. Returns the
    file path, or None."""
    from datetime import timedelta
    from education_system.systems.university.domains.student_support.domain.helpdesk.tickets.service import (
        ticket_counts,
    )
    from education_system.systems.university.domains.student_support.domain.student_support import (
        routing, schema,
    )
    try:
        days = int(period)
    except (TypeError, ValueError):
        days = _PERIOD_DAYS.get(str(period or '').strip().lower(), 30)
    start = (datetime.now() - timedelta(days=days)).strftime('%Y-%m-%d %H:%M:%S')
    filters = {'date_from': start}
    try:
        total = ticket_counts(auth, filters=filters)
        sections = [
            ("By status", {schema.status_label(k): v for k, v in
                           ticket_counts(auth, by='status', filters=filters).items()}),
            ("By priority", ticket_counts(auth, by='priority', filters=filters)),
            ("By category", ticket_counts(auth, by='category', filters=filters)),
            ("By team", {routing.team_label(k) if k else 'Unrouted': v for k, v in
                         ticket_counts(auth, by='team', filters=filters).items()}),
        ]
    except (PermissionError, ValueError) as e:
        print(f"Error saving report: {e}")
        return None
    try:
        from education_system import paths
        paths.UNIVERSITY_REPORTS_DIR.mkdir(parents=True, exist_ok=True)
        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
        filename = str(paths.UNIVERSITY_REPORTS_DIR / f"{report_type}_{period}_{timestamp}.txt")
        with open(filename, 'w', encoding='utf-8') as f:
            f.write(f"Helpdesk Report: {report_type}\n")
            f.write(f"Period: {period} (tickets raised since {start})\n")
            f.write(f"Generated by: {auth.current_user['username']}\n")
            f.write(f"Generated at: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
            f.write("\n" + "=" * 50 + "\n\n")
            f.write(f"Tickets: {total}\n")
            for title, counts in sections:
                f.write(f"\n{title}:\n")
                for key, n in counts.items():
                    f.write(f"  {key or '(none)'}: {n}\n")
        print(f"Report saved to {filename}")
        return filename
    except OSError as e:
        print(f"Error saving report: {e}")
        return None
