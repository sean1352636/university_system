"""
Report generation for support analytics.

The older reports (ticket summary, performance, satisfaction, category
analysis) are kept; :func:`service_report` adds the service-level picture:
volumes by team / category / channel, first-response and resolution times
against the SLA, breaches, backlog age, satisfaction with the survey
response rate, the self-help deflection rate and themes. Everything is an
aggregate count; the only text used is keywords from the titles of
standard-tier tickets (never restricted or safeguarding ones).
"""

