logger = logging.getLogger(__name__)

def generate_reports(report_type, date_range, filters=None):
    """Generate various types of reports"""
    if not _auth_mod.auth or not _auth_mod.auth.current_user or not _auth_mod.is_support_staff():
        raise PermissionError("You must be staff or admin to generate reports")

    try:
        generators = {
            'ticket_summary': _generate_ticket_summary_report,
            'performance': _generate_performance_report,
            'satisfaction': _generate_satisfaction_report,
            'category_analysis': _generate_category_analysis_report,
            'service_levels': _generate_service_report,
        }
        if report_type not in generators:
            raise ValueError(f"Unknown report type: {report_type}")
        from education_system.systems.university.domains.student_support.domain.student_support import (
            store,
        )
        conn = store.connect()
        try:
            report_data = generators[report_type](conn.cursor(), date_range, filters)
        finally:
            conn.close()

        # Record report generation
        _log_report_generation(report_type, _auth_mod.auth.current_user['username'])

        logger.info(f"Report '{report_type}' generated by {_auth_mod.auth.current_user['username']}")
        return report_data

    except Exception as e:
        logger.error(f"Error generating report: {e}")
        raise

def _generate_ticket_summary_report(cursor, date_range, filters):
    """Generate ticket summary report"""
    date_params = (date_range['start'], date_range['end'])

    # Total tickets
    cursor.execute('SELECT COUNT(*) FROM support_tickets WHERE created_at BETWEEN ? AND ?', date_params)
    total_tickets = cursor.fetchone()[0]

    # Tickets by status
    cursor.execute('SELECT status, COUNT(*) FROM support_tickets WHERE created_at BETWEEN ? AND ? GROUP BY status', date_params)
    status_breakdown = dict(cursor.fetchall())

    # Tickets by category
    cursor.execute('SELECT category, COUNT(*) FROM support_tickets WHERE created_at BETWEEN ? AND ? GROUP BY category', date_params)
    category_breakdown = dict(cursor.fetchall())

    # Tickets by priority
    cursor.execute('SELECT priority, COUNT(*) FROM support_tickets WHERE created_at BETWEEN ? AND ? GROUP BY priority', date_params)
    priority_breakdown = dict(cursor.fetchall())

    # Daily ticket creation
    cursor.execute('''
    SELECT DATE(created_at) as date, COUNT(*) as count
    FROM support_tickets
    WHERE created_at BETWEEN ? AND ?
    GROUP BY DATE(created_at)
    ORDER BY date
    ''', date_params)
    daily_creation = [{'date': row[0], 'count': row[1]} for row in cursor.fetchall()]

    return {
        'total_tickets': total_tickets,
        'status_breakdown': status_breakdown,
        'category_breakdown': category_breakdown,
        'priority_breakdown': priority_breakdown,
        'daily_creation': daily_creation,
        'date_range': date_range
    }

def _generate_performance_report(cursor, date_range, filters):
    """Generate performance metrics report"""
    date_params = (date_range['start'], date_range['end'])

    # Resolution time statistics
    cursor.execute('''
    SELECT
        AVG(julianday(resolved_at) - julianday(created_at)) * 24 as avg_hours,
        MIN(julianday(resolved_at) - julianday(created_at)) * 24 as min_hours,
        MAX(julianday(resolved_at) - julianday(created_at)) * 24 as max_hours,
        COUNT(*) as resolved_count
    FROM support_tickets
    WHERE created_at BETWEEN ? AND ? AND resolved_at IS NOT NULL
    ''', date_params)

    resolution_stats = cursor.fetchone()

    # Staff performance
    cursor.execute('''
    SELECT
        assigned_to,
        COUNT(*) as total_assigned,
        COUNT(CASE WHEN status IN ('resolved', 'closed') THEN 1 END) as resolved,
        AVG(CASE WHEN resolved_at IS NOT NULL
            THEN julianday(resolved_at) - julianday(created_at)
            END) * 24 as avg_resolution_hours
    FROM support_tickets
    WHERE created_at BETWEEN ? AND ? AND assigned_to IS NOT NULL
    GROUP BY assigned_to
    ''', date_params)

    staff_performance = [
        {
            'staff_member': row[0],
            'total_assigned': row[1],
            'resolved': row[2],
            'resolution_rate': round(row[2] / row[1] * 100, 1) if row[1] > 0 else 0,
            'avg_resolution_hours': round(row[3] or 0, 1)
        }
        for row in cursor.fetchall()
    ]

    return {
        'resolution_stats': {
            'avg_hours': round(resolution_stats[0] or 0, 1),
            'min_hours': round(resolution_stats[1] or 0, 1),
            'max_hours': round(resolution_stats[2] or 0, 1),
            'resolved_count': resolution_stats[3]
        },
        'staff_performance': staff_performance,
        'date_range': date_range
    }

def _generate_satisfaction_report(cursor, date_range, filters):
    """Generate satisfaction survey report"""
    date_params = (date_range['start'], _end(date_range['end']))

    # Ratings of tickets resolved in the period
    cursor.execute('''
    SELECT
        AVG(satisfaction_rating) as avg_rating,
        COUNT(satisfaction_rating) as response_count,
        COUNT(*) as total_resolved
    FROM support_tickets
    WHERE resolved_at BETWEEN ? AND ?
    ''', date_params)

    satisfaction_data = cursor.fetchone()

    # Rating distribution
    cursor.execute('''
    SELECT satisfaction_rating, COUNT(*)
    FROM support_tickets
    WHERE resolved_at BETWEEN ? AND ? AND satisfaction_rating IS NOT NULL
    GROUP BY satisfaction_rating
    ORDER BY satisfaction_rating
    ''', date_params)

    rating_distribution = dict(cursor.fetchall())
    surveys = _survey_counts(cursor.connection, date_range['start'], date_range['end'])

    return {
        'avg_rating': round(satisfaction_data[0] or 0, 2),
        # Rated tickets out of those resolved in the period (it used to count
        # only rated tickets, so it always read 100%).
        'response_rate': round((satisfaction_data[1] or 0) / max(satisfaction_data[2] or 0, 1) * 100, 1),
        'total_responses': satisfaction_data[1],
        'total_resolved': satisfaction_data[2],
        'surveys_sent': surveys['sent'],
        'survey_response_rate': surveys['response_rate'],
        'rating_distribution': rating_distribution,
        'date_range': date_range
    }

def _generate_category_analysis_report(cursor, date_range, filters):
    """Generate category analysis report"""
    date_params = (date_range['start'], date_range['end'])

    # Category statistics
    cursor.execute('''
    SELECT
        category,
        COUNT(*) as total_tickets,
        COUNT(CASE WHEN status IN ('resolved', 'closed') THEN 1 END) as resolved,
        AVG(CASE WHEN resolved_at IS NOT NULL
            THEN julianday(resolved_at) - julianday(created_at)
            END) * 24 as avg_resolution_hours,
        AVG(satisfaction_rating) as avg_satisfaction
    FROM support_tickets
    WHERE created_at BETWEEN ? AND ?
    GROUP BY category
    ORDER BY total_tickets DESC
    ''', date_params)

    category_stats = [
        {
            'category': row[0],
            'total_tickets': row[1],
            'resolved': row[2],
            'resolution_rate': round(row[2] / row[1] * 100, 1) if row[1] > 0 else 0,
            'avg_resolution_hours': round(row[3] or 0, 1),
            'avg_satisfaction': round(row[4] or 0, 2)
        }
        for row in cursor.fetchall()
    ]

    return {
        'category_stats': category_stats,
        'date_range': date_range
    }

def _end(day) -> str:
    """The last moment of ``day`` ('2026-10-19' -> '2026-10-19 23:59:59')."""
    day = str(day)
    return day if len(day) > 10 else f"{day} 23:59:59"


def _survey_counts(conn, start, end) -> dict:
    """Surveys sent in the period and how many of those tickets were rated."""
    from education_system.systems.university.domains.student_support.domain.student_support import (
        notify,
    )
    rows = conn.execute(
        "SELECT DISTINCT CAST(m.metric_value AS INTEGER), t.satisfaction_rating "
        "FROM system_metrics m LEFT JOIN support_tickets t "
        "ON t.ticket_id = CAST(m.metric_value AS INTEGER) "
        "WHERE m.metric_name = ? AND m.recorded_datetime BETWEEN ? AND ?",
        (notify.SURVEY_METRIC, str(start), _end(end))).fetchall()
    sent = len({r[0] for r in rows})
    answered = len({r[0] for r in rows if r[1] is not None})
    return {'sent': sent, 'answered': answered,
            'response_rate': round(100 * answered / sent, 1) if sent else 0.0}


_THEME_STOP = {'ticket', 'issue', 'problem', 'request', 'question', 'query', 'support'}
_BACKLOG_BUCKETS = (('under 1 day', 1), ('1-3 days', 3), ('3-7 days', 7), ('7-14 days', 14),
                    ('over 14 days', None))


def _pct(part, whole):
    return round(100 * part / whole, 1) if whole else 0.0


def _avg(values):
    return round(sum(values) / len(values), 1) if values else None


def _generate_service_report(cursor, date_range, filters):
    """Service levels for tickets raised in the period (see the module notes)."""
    from collections import Counter
    from education_system.systems.university.domains.student_support.domain.student_support import (
        deflection,
        routing,
        schema,
        sla,
    )
    conn = cursor.connection
    start, end = str(date_range['start']), _end(date_range['end'])
    team_filter = routing.team_key((filters or {}).get('team')) if (filters or {}).get('team') else None
    now = datetime.datetime.now()
    clock = sla.Clock(conn)

    def team_of(t):
        return t['team'] or routing.route(t['category'], t['subcategory'])

    rows = [t for t in conn.execute(
        "SELECT * FROM support_tickets WHERE created_at BETWEEN ? AND ?", (start, end)).fetchall()
        if team_filter is None or team_of(t) == team_filter]
    by_team, by_category, by_channel, by_source = Counter(), Counter(), Counter(), Counter()
    fr_hours, res_hours = [], []
    fr_met = fr_due = res_met = res_due = fr_breach = res_breach = 0
    weekly = {}
    words = Counter()
    for t in rows:
        team = team_of(t)
        by_team[routing.team_label(team)] += 1
        by_category[routing.category_label(t['category'])] += 1
        by_channel[t['channel'] or t['source'] or 'unknown'] += 1
        by_source[t['source'] or 'unknown'] += 1
        week = (sla.parse(t['created_at']) or now).strftime('%G-W%V')
        weekly.setdefault(week, Counter())[routing.category_label(t['category'])] += 1
        state = sla.ticket_sla(conn, t, now, clock)
        business = state['targets']['business_hours_only']
        created = sla.parse(t['created_at'])
        first = sla.parse(t['first_response_at'])
        done_at = sla.parse(t['resolved_at']) or sla.parse(t['closed_at'])
        if created and first:
            fr_hours.append(clock.hours_between(created, first, business))
        if created and done_at:
            res_hours.append(clock.hours_between(created, done_at, business))
        if state['first_response_met'] is not None:
            fr_due += 1
            fr_met += 1 if state['first_response_met'] else 0
        if state['resolution_met'] is not None:
            res_due += 1
            res_met += 1 if state['resolution_met'] else 0
        fr_breach += 1 if state['first_response_breached'] else 0
        res_breach += 1 if state['resolution_breached'] else 0
        private = t['confidentiality'] in ('restricted', 'safeguarding') or t['crisis_flag']
        if not private:
            words.update(w for w in deflection.keywords(t['subject'], limit=20)
                         if w not in _THEME_STOP)

    # Backlog: every ticket still open now, by age.
    marks = ", ".join("?" * len(schema.ACTIVE_STATUSES))
    active = [t for t in conn.execute(
        f"SELECT * FROM support_tickets WHERE status IN ({marks})",  # nosec B608
        schema.ACTIVE_STATUSES).fetchall() if team_filter is None or team_of(t) == team_filter]
    ages = [(now - (sla.parse(t['created_at']) or now)).total_seconds() / 86400 for t in active]
    backlog = dict.fromkeys((b[0] for b in _BACKLOG_BUCKETS), 0)
    for age in ages:
        for label, limit in _BACKLOG_BUCKETS:
            if limit is None or age < limit:
                backlog[label] += 1
                break

    fires = dict(conn.execute(
        "SELECT action_type, COUNT(*) FROM support_escalation_fires WHERE rule_id < 0 "
        "AND fired_at BETWEEN ? AND ? GROUP BY action_type", (start, end)).fetchall())
    rated = [t['satisfaction_rating'] for t in rows if t['satisfaction_rating'] is not None]
    surveys = _survey_counts(conn, start, end)
    return {
        'date_range': date_range, 'team': team_filter, 'total_tickets': len(rows),
        'volumes': {'by_team': dict(by_team.most_common()),
                    'by_category': dict(by_category.most_common()),
                    'by_channel': dict(by_channel.most_common()),
                    'by_source': dict(by_source.most_common())},
        'first_response': {'avg_hours': _avg(fr_hours), 'responded': len(fr_hours),
                           'measured': fr_due, 'met': fr_met, 'met_pct': _pct(fr_met, fr_due),
                           'breached': fr_breach},
        'resolution': {'avg_hours': _avg(res_hours), 'resolved': len(res_hours),
                       'measured': res_due, 'met': res_met, 'met_pct': _pct(res_met, res_due),
                       'breached': res_breach},
        'breach_alerts': {'first_response': fires.get('sla_first_response_breach', 0),
                          'resolution': fires.get('sla_resolution_breach', 0),
                          'warnings': fires.get('sla_first_response_warning', 0)
                          + fires.get('sla_resolution_warning', 0)},
        'backlog': {'open': len(active), 'by_age': backlog,
                    'oldest_days': round(max(ages), 1) if ages else 0,
                    'avg_age_days': _avg(ages) or 0},
        'satisfaction': {'avg_rating': round(sum(rated) / len(rated), 2) if rated else None,
                         'ratings': len(rated), 'surveys_sent': surveys['sent'],
                         'surveys_answered': surveys['answered'],
                         'response_rate': surveys['response_rate']},
        'deflection': deflection.stats(conn, start, end),
        'themes': {'top_keywords': dict(words.most_common(15)),
                   'top_categories': dict(by_category.most_common(5)),
                   'by_week': {w: dict(c.most_common(5)) for w, c in sorted(weekly.items())}},
    }


def service_report(actor, date_from, date_to, team=None) -> dict:
    """:func:`_generate_service_report` for support staff (``team`` optional)."""
    from education_system.systems.university.domains.student_support.domain.student_support import (
        store,
    )
    if not _auth_mod.is_support_staff(actor):
        raise PermissionError("You must be staff or admin to generate reports")
    with store.reading() as conn:
        return _generate_service_report(conn.cursor(), {'start': str(date_from), 'end': str(date_to)},
                                        {'team': team} if team else None)


def _log_report_generation(report_type, user_id):
    """Log report generation for audit"""
    from education_system.systems.university.domains.student_support.domain.student_support import store
    try:
        with store.writing() as conn:
            conn.execute('''
            INSERT INTO system_metrics (
                metric_name, metric_value, category, recorded_datetime, metadata
            ) VALUES (?, ?, ?, ?, ?)
            ''', (
                'report_generated', 1, 'reports',
                datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
                json.dumps({'report_type': report_type, 'user_id': user_id})
            ))
    except Exception as e:
        logger.error(f"Error logging report generation: {e}")

def generate_reports_menu(support):
    """Generate reports menu"""
    try:
        print("\n📊 GENERATE REPORTS")
        print("="*40)
        print("1. Ticket Summary Report")
        print("2. Performance Report")
        print("3. Satisfaction Report")
        print("4. Category Analysis Report")
        print("5. Back")
        print("6. Service Levels Report (SLA, backlog, satisfaction, deflection, themes)")

        choice = input("\nSelect report type: ").strip()

        if choice == '5':
            return

        report_types = {
            '1': 'ticket_summary',
            '2': 'performance',
            '3': 'satisfaction',
            '4': 'category_analysis',
            '6': 'service_levels'
        }

        report_type = report_types.get(choice)
        if not report_type:
            print("❌ Invalid choice.")
            return

        # Date range
        print("\nDate Range:")
        start_date = input("Start date (YYYY-MM-DD) [30 days ago]: ").strip()
        if not start_date:
            start_date = (datetime.datetime.now() - datetime.timedelta(days=30)).strftime('%Y-%m-%d')

        end_date = input("End date (YYYY-MM-DD) [today]: ").strip()
        if not end_date:
            end_date = datetime.datetime.now().strftime('%Y-%m-%d')

        date_range = {'start': start_date, 'end': end_date}

        print(f"\n📈 Generating {report_type} report...")
        report_data = support.generate_reports(report_type, date_range)

        # Display report summary
        print(f"\n📋 REPORT: {report_type.upper()}")
        print("="*50)

        if report_type == 'ticket_summary':
            print(f"📊 Total Tickets: {report_data['total_tickets']}")
            print(f"📈 Status Breakdown: {report_data['status_breakdown']}")
            print(f"📁 Category Breakdown: {report_data['category_breakdown']}")

        elif report_type == 'performance':
            stats = report_data['resolution_stats']
            print(f"⏱️ Average Resolution Time: {stats['avg_hours']} hours")
            print(f"✅ Resolved Tickets: {stats['resolved_count']}")
            print(f"👥 Staff Performance: {len(report_data['staff_performance'])} staff members")

        elif report_type == 'satisfaction':
            print(f"⭐ Average Rating: {report_data['avg_rating']}/5")
            print(f"📊 Response Rate: {report_data['response_rate']}%")
            print(f"📝 Total Responses: {report_data['total_responses']}")
            print(f"📨 Surveys sent: {report_data['surveys_sent']} "
                  f"(answered {report_data['survey_response_rate']}%)")

        elif report_type == 'service_levels':
            fr, res = report_data['first_response'], report_data['resolution']
            print(f"📊 Tickets: {report_data['total_tickets']}  by team: {report_data['volumes']['by_team']}")
            print(f"⏱️ First response: avg {fr['avg_hours']} h, {fr['met_pct']}% within SLA, "
                  f"{fr['breached']} breached")
            print(f"✅ Resolution: avg {res['avg_hours']} h, {res['met_pct']}% within SLA, "
                  f"{res['breached']} breached")
            print(f"📥 Backlog: {report_data['backlog']['open']} open {report_data['backlog']['by_age']}")
            sat = report_data['satisfaction']
            print(f"⭐ Satisfaction: {sat['avg_rating']} from {sat['ratings']} ratings; "
                  f"survey response rate {sat['response_rate']}%")
            print(f"📚 Deflection rate: {report_data['deflection']['deflection_rate']}%")
            print(f"🔎 Themes: {report_data['themes']['top_keywords']}")

        # Export option
        export_choice = input("\nExport report? (y/n): ").lower()
        if export_choice == 'y':
            filename = f"{report_type}_report_{start_date}_to_{end_date}.json"
            with open(filename, 'w') as f:
                json.dump(report_data, f, indent=2)
            print(f"✅ Report exported to {filename}")

    except Exception as e:
        print(f"❌ Error generating report: {e}")

    input("\nPress Enter to continue...")
