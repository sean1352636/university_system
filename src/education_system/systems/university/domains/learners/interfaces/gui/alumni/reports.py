        def _email_report_to_admin(self, output_widget=None):
            """Email current report to admin via the email system."""
            widget = output_widget if output_widget is not None else self.report_output
            parent = widget.winfo_toplevel()
            report_content = widget.get(1.0, tk.END).strip()
            if not report_content or report_content.startswith("Select a quick report"):
                messagebox.showwarning(_t('gui.learners.alumni.reports.dialogs.no_report', default="No Report"), _t('gui.learners.alumni.reports.dialogs.please_generate_a_report_first_before_emailing', default="Please generate a report first before emailing."), parent=parent)
                return

            try:
                # Import required modules
                from education_system.systems.university.infrastructure.database.db import get_connection
                from education_system.systems.university.infrastructure.email.email_service import send_email

                # Get admin email from database
                admin_email = None
                try:
                    with get_connection() as conn:
                        cursor = conn.execute("""
                            SELECT email FROM users
                            WHERE role = 'admin' AND email IS NOT NULL AND email != ''
                            LIMIT 1
                        """)
                        admin_row = cursor.fetchone()
                        if admin_row and admin_row[0]:
                            admin_email = admin_row[0]
                except sqlite3.Error as e:
                    print(f"Warning: Could not fetch admin email: {e}")

                # Fall back to the canonical configured admin address.
                if not admin_email:
                    try:
                        from education_system.systems.university.infrastructure.defaults import get_admin_email
                        admin_email = get_admin_email()
                    except Exception:
                        admin_email = None

                if not admin_email:
                    messagebox.showerror(_t('gui.learners.alumni.reports.dialogs.error', default="Error"), _t('gui.learners.alumni.reports.dialogs.no_admin_email_found', default="No admin email found"), parent=parent)
                    return

                # Use template for email
                template_vars = {
                    'report_date': datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
                    'report_content': report_content
                }

                subject, body = render_template('alumni_report_admin', template_vars)

                if not subject or not body:
                    # Fallback if template fails
                    subject = f"Alumni Report - {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
                    body = f"Alumni Report\n\nGenerated by: Alumni Management System\nDate: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n"
                    body += "-" * 50 + "\n\n"
                    body += report_content

                result = send_email(admin_email, subject, body)

                if result:
                    messagebox.showinfo(_t('gui.learners.alumni.reports.dialogs.success', default="Success"), f"Report emailed successfully to {admin_email}", parent=parent)
                else:
                    messagebox.showinfo(_t('gui.learners.alumni.reports.dialogs.queued', default="Queued"), f"Report has been queued for delivery to {admin_email}", parent=parent)

            except ImportError:
                messagebox.showerror(_t('gui.learners.alumni.reports.dialogs.error', default="Error"), _t('gui.learners.alumni.reports.dialogs.email_service_is_not_available_please_check_email_configuration', default="Email service is not available. Please check email configuration."), parent=parent)
            except (sqlite3.Error, AttributeError) as e:
                messagebox.showerror(_t('gui.learners.alumni.reports.dialogs.error', default="Error"), f"Failed to send email: {str(e)}", parent=parent)


        # ── report data (university/application/alumni/reports) ────────

        def _report_parent(self):
            win = getattr(self, "reports_window", None)
            try:
                if win is not None and win.winfo_exists():
                    return win
            except tk.TclError:
                pass
            return self.root

        def _report_range(self):
            """The custom builder's date range ('' = open-ended)."""
            start = getattr(self, "report_start_date", None)
            end = getattr(self, "report_end_date", None)
            return (start.get().strip() if start is not None else "",
                    end.get().strip() if end is not None else "")

        def _run_report(self, kind, sections=None, use_range=False):
            """Build a report from the live alumni records; ``None`` if it was
            refused or failed (the error has already been shown)."""
            from education_system.systems.university.application.alumni import reports as rules
            from education_system.systems.university.infrastructure.ui import record_screens
            start, end = self._report_range() if use_range else ("", "")
            builders = {
                'summary': lambda conn: rules.summary_report(conn, self.who),
                'engagement': lambda conn: rules.engagement_report(conn, self.who, start, end),
                'donation': lambda conn: rules.giving_report(conn, self.who, start, end),
                'events': lambda conn: rules.events_report(conn, self.who, start, end),
                'usage': lambda conn: rules.usage_report(conn, self.who),
                'custom': lambda conn: rules.custom_report(conn, self.who, sections or [],
                                                           start, end),
            }
            data = record_screens.call(self._report_parent(), builders[kind])
            if data is None or data is True:
                return None
            return data

        def _report_text(self, kind, sections=None, use_range=False, giving_full=True):
            from education_system.systems.university.application.alumni import reports as rules
            data = self._run_report(kind, sections, use_range)
            if data is None:
                return "The report could not be generated (see the message shown)."
            return rules.render(data, giving_full=giving_full)

        def _selected_sections(self):
            sections = getattr(self, "report_sections", {}) or {}
            return [key for key, var in sections.items() if var.get()]

        def _show_in_output(self, content, status):
            self.report_output.delete(1.0, tk.END)
            self.report_output.insert(tk.END, content)
            self.update_status(status)

        def _generate_custom_report_content(self):
            """Generate custom report based on selected sections"""
            self.report_output.insert(tk.END, self._build_custom_report_text())

        def _generate_donation_report_content(self):
            """Generate donation report content"""
            self.report_output.insert(tk.END, self._get_donation_report_text())

        def _generate_engagement_report_content(self):
            """Generate engagement report content"""
            self.report_output.insert(tk.END, self._get_engagement_report_text())

        def _generate_report_in_window(self, report_type):
            """Generate the report and open it in its own window."""
            if report_type == 'summary':
                content = self._get_alumni_summary_text()
            elif report_type == 'engagement':
                content = self._get_engagement_report_text()
            elif report_type == 'donation':
                content = self._get_donation_report_text()
            elif report_type == 'events':
                content = self._report_text('events', use_range=True)
            elif report_type == 'custom':
                content = self._build_custom_report_text()
            else:
                content = "Unknown report type."
            self._open_report_window(report_type, content)

        def _open_report_window(self, report_type, content):
            """Show a generated report in a new window with Save-as-TXT and
            Email-to-Admin actions wired to the email system."""
            win = tk.Toplevel(self.root)
            win.title(f"{str(report_type).title()} Report")
            win.geometry("820x620")
            out = ScrolledText(win, wrap=tk.WORD)
            out.pack(fill=tk.BOTH, expand=True, padx=10, pady=10)
            out.insert(tk.END, content)

            btns = ttk.Frame(win)
            btns.pack(fill=tk.X, padx=10, pady=(0, 10))
            ttk.Button(btns, text=_t('gui.learners.alumni.reports.buttons.save_as_txt', default="💾 Save as TXT"),
                       command=lambda: self._save_report_as_txt(out)).pack(side=tk.LEFT, padx=(0, 10))
            ttk.Button(btns, text=_t('gui.learners.alumni.reports.buttons.email_to_admin', default="✉ Email to Admin"),
                       command=lambda: self._email_report_to_admin(out)).pack(side=tk.LEFT, padx=(0, 10))
            ttk.Button(btns, text=_t('gui.learners.alumni.reports.buttons.close', default="Close"), command=win.destroy).pack(side=tk.RIGHT)

            # Mirror into the inline panel too, if the reports view built one.
            try:
                self.report_output.delete(1.0, tk.END)
                self.report_output.insert(tk.END, content)
            except (AttributeError, tk.TclError):
                pass


        def _build_custom_report_text(self):
            """Build the custom report text from the selected sections."""
            selected = self._selected_sections()
            if not selected:
                return "Please select at least one section to include in the report."
            return self._report_text('custom', sections=selected, use_range=True)

        def _generate_summary_report_content(self):
            """Generate summary report content"""
            self.report_output.insert(tk.END, self._get_alumni_summary_text())

        def _get_alumni_summary_text(self):
            """Return alumni summary report text"""
            return self._report_text('summary')

        def _get_donation_report_text(self):
            """Return donation report text"""
            return self._report_text('donation', use_range=True, giving_full=False)

        def _get_engagement_report_text(self):
            """Return engagement report text"""
            return self._report_text('engagement', use_range=True)

        def _save_report_as_txt(self, output_widget=None):
            """Save current report as a TXT file"""
            widget = output_widget if output_widget is not None else self.report_output
            parent = widget.winfo_toplevel()
            report_content = widget.get(1.0, tk.END).strip()
            if not report_content or report_content.startswith("Select a quick report"):
                messagebox.showwarning(_t('gui.learners.alumni.reports.dialogs.no_report', default="No Report"), _t('gui.learners.alumni.reports.dialogs.please_generate_a_report_first_before_saving', default="Please generate a report first before saving."), parent=parent)
                return

            file_path = filedialog.asksaveasfilename(
                parent=parent,
                defaultextension=".txt",
                filetypes=[("Text files", "*.txt"), ("All files", "*.*")],
                initialfile=f"alumni_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.txt"
            )

            if file_path:
                try:
                    with open(file_path, 'w', encoding='utf-8') as f:
                        f.write(report_content)
                    messagebox.showinfo(_t('gui.learners.alumni.reports.dialogs.success', default="Success"), f"Report saved successfully to:\n{file_path}", parent=parent)
                except (OSError, IOError) as e:
                    messagebox.showerror(_t('gui.learners.alumni.reports.dialogs.file_error', default="File Error"), f"Failed to save report: {str(e)}", parent=parent)


