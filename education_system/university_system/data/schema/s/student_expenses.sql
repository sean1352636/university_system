CREATE TABLE IF NOT EXISTS student_expenses (
                        expense_id INTEGER PRIMARY KEY AUTOINCREMENT,
                        student_id TEXT NOT NULL,
                        budget_id INTEGER,
                        category_id INTEGER,
                        expense_date TEXT NOT NULL,
                        amount REAL NOT NULL,
                        merchant_name TEXT,
                        description TEXT,
                        payment_method TEXT CHECK(payment_method IN ('cash', 'debit', 'credit', 'meal-plan', 'financial-aid', 'other')),
                        receipt_url TEXT,
                        is_recurring BOOLEAN DEFAULT 0,
                        recurrence_pattern TEXT,
                        tags TEXT,
                        location TEXT,
                        notes TEXT,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        FOREIGN KEY (student_id) REFERENCES students(student_id),
                        FOREIGN KEY (budget_id) REFERENCES student_budgets(budget_id),
                        FOREIGN KEY (category_id) REFERENCES budget_categories(category_id)
                    );
