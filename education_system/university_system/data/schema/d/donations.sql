CREATE TABLE IF NOT EXISTS donations (
            donation_id INTEGER PRIMARY KEY AUTOINCREMENT,
            alumni_id TEXT,
            amount REAL,
            donation_date TEXT,
            campaign TEXT,
            campaign_id INTEGER,
            payment_method TEXT,
            is_recurring BOOLEAN,
            recurring_frequency TEXT,
            receipt_sent BOOLEAN,
            notes TEXT,
            donation_type TEXT DEFAULT 'general',
            tribute_type TEXT,
            tribute_name TEXT,
            employer_match_eligible BOOLEAN DEFAULT 0,
            employer_match_amount REAL DEFAULT 0.0,
            recognition_level TEXT, is_gift_aided INTEGER DEFAULT 0,
            FOREIGN KEY (alumni_id) REFERENCES alumni (alumni_id),
            FOREIGN KEY (campaign_id) REFERENCES fundraising_campaigns (campaign_id)
        );
