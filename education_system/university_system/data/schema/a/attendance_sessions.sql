CREATE TABLE IF NOT EXISTS attendance_sessions (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            session_id TEXT UNIQUE,
            module_code TEXT,
            date TEXT,
            start_time TEXT,
            end_time TEXT,
            location_name TEXT,
            latitude REAL,
            longitude REAL,
            geofence_radius INTEGER DEFAULT 50,
            qr_code_data TEXT,
            qr_code_expires TEXT,
            session_type TEXT DEFAULT 'lecture',
            max_capacity INTEGER,
            created_by TEXT,
            created_at TEXT DEFAULT CURRENT_TIMESTAMP,
            status TEXT DEFAULT 'active', "beacon_id" TEXT, "geofence_latitude" REAL, "geofence_longitude" REAL, "geofence_radius_meters" INTEGER DEFAULT 50, "location" TEXT, "qr_code" TEXT, "qr_code_expires_at" TEXT, "require_facial_recognition" BOOLEAN DEFAULT 0, "session_date" TEXT, "session_time" TEXT,
            FOREIGN KEY (module_code) REFERENCES modules (module_code)
        );
