CREATE TABLE IF NOT EXISTS books (
            book_id TEXT PRIMARY KEY,
            title TEXT NOT NULL,
            author TEXT NOT NULL,
            isbn TEXT UNIQUE,
            publisher TEXT,
            category TEXT,
            year_published INTEGER,
            description TEXT,
            location TEXT,
            status TEXT DEFAULT 'available',
            added_date TEXT,
            last_updated TEXT,
            reading_level TEXT,
            tags TEXT,
            cover_image_path TEXT,
            digital_copy_path TEXT,
            acquisition_cost REAL DEFAULT 0.0,
            barcode TEXT UNIQUE,
            qr_code_path TEXT,
            total_pages INTEGER,
            language TEXT DEFAULT 'English',
            edition TEXT,
            condition_notes TEXT
        , purchase_price REAL DEFAULT 0.0, purchase_date TEXT, supplier TEXT, quantity INTEGER DEFAULT 1);
