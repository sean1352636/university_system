CREATE TABLE IF NOT EXISTS orders (
    order_id INTEGER PRIMARY KEY AUTOINCREMENT,
    source_type TEXT NOT NULL,
    source_order_id TEXT,
    order_number TEXT,
    customer_id TEXT,
    customer_name TEXT,
    customer_email TEXT,
    customer_phone TEXT,
    student_id TEXT,
    user_id INTEGER,
    restaurant_id TEXT,
    order_type TEXT,
    order_date TEXT DEFAULT (datetime('now')),
    subtotal REAL,
    tax_amount REAL,
    shipping_fee REAL,
    delivery_fee REAL,
    discount_amount REAL,
    total_amount REAL,
    payment_method TEXT,
    payment_status TEXT,
    payment_reference TEXT,
    order_status TEXT DEFAULT 'pending',
    delivery_address TEXT,
    shipping_address TEXT,
    delivery_type TEXT,
    estimated_delivery TEXT,
    actual_delivery TEXT,
    pickup_date TEXT,
    pickup_time TEXT,
    special_instructions TEXT,
    age_verified INTEGER,
    rating INTEGER,
    review TEXT,
    notes TEXT,
    processed_by TEXT,
    created_by TEXT,
    created_at TEXT DEFAULT (datetime('now')),
    updated_at TEXT
, "id" INTEGER, "completed_at" TIMESTAMP, "items" TEXT);
