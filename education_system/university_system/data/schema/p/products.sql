CREATE TABLE IF NOT EXISTS products (
    product_id INTEGER PRIMARY KEY AUTOINCREMENT,
    source_type TEXT NOT NULL,
    source_product_id TEXT,
    sku TEXT,
    name TEXT NOT NULL,
    description TEXT,
    category TEXT,
    brand TEXT,
    artist TEXT,
    model TEXT,
    genre TEXT,
    format TEXT,
    label TEXT,
    release_year INTEGER,
    condition TEXT,
    price REAL,
    cost_price REAL,
    price_per_unit REAL,
    unit_type TEXT,
    unit TEXT,
    tax_rate REAL,
    stock_quantity REAL,
    min_stock_level REAL,
    barcode TEXT,
    is_available INTEGER DEFAULT 1,
    is_active INTEGER DEFAULT 1,
    is_alcoholic INTEGER,
    is_perishable INTEGER,
    is_rare INTEGER,
    is_vegetarian INTEGER,
    is_vegan INTEGER,
    is_gluten_free INTEGER,
    calories INTEGER,
    allergens TEXT,
    origin TEXT,
    storage_temp TEXT,
    shelf_life_days INTEGER,
    expiry_date TEXT,
    discount_percentage REAL,
    specifications TEXT,
    warranty_months INTEGER,
    image_url TEXT,
    restaurant_id TEXT,
    category_id TEXT,
    notes TEXT,
    created_at TEXT DEFAULT (datetime('now')),
    updated_at TEXT
);
