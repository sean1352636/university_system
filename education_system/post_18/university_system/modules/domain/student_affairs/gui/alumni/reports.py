        def _email_report_to_admin(self, output_widget=None):
            """Email current report to admin via the email system."""
            widget = output_widget if output_widget is not None else self.report_output
            report_content = widget.get(1.0, tk.END).strip()
            if not report_content or report_content.startswith("Select a quick report"):
                messagebox.showwarning("No Report", "Please generate a report first before emailing.")
                return

            try:
                # Import required modules
                from education_system.post_18.university_system.infrastructure.database.db import get_connection
                from education_system.post_18.university_system.infrastructure.email.email_service import send_email

                # Get admin email from database
                admin_email = None
                try:
                    with get_connection() as conn:
                        cursor = conn.execute("""
                            SELECT email FROM users
                            WHERE role = 'admin' AND email IS NOT NULL AND email != ''
                            LIMIT 1
                        """)
                        admin_row = cursor.fetchone()
                        if admin_row and admin_row[0]:
                            admin_email = admin_row[0]
                except sqlite3.Error as e:
                    print(f"Warning: Could not fetch admin email: {e}")

                # Fall back to the canonical configured admin address.
                if not admin_email:
                    try:
                        from education_system.post_18.university_system.core.defaults import get_admin_email
                        admin_email = get_admin_email()
                    except Exception:
                        admin_email = None

                if not admin_email:
                    messagebox.showerror("Error", "No admin email found")
                    return

                # Use template for email
                template_vars = {
                    'report_date': datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
                    'report_content': report_content
                }

                subject, body = render_template('alumni_report_admin', template_vars)

                if not subject or not body:
                    # Fallback if template fails
                    subject = f"Alumni Report - {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
                    body = f"Alumni Report\n\nGenerated by: Alumni Management System\nDate: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n"
                    body += "-" * 50 + "\n\n"
                    body += report_content

                result = send_email(admin_email, subject, body)

                if result:
                    messagebox.showinfo("Success", f"Report emailed successfully to {admin_email}")
                else:
                    messagebox.showinfo("Queued", f"Report has been queued for delivery to {admin_email}")

            except ImportError:
                messagebox.showerror("Error", "Email service is not available. Please check email configuration.")
            except (sqlite3.Error, AttributeError) as e:
                messagebox.showerror("Error", f"Failed to send email: {str(e)}")

