        def _generate_report_in_window(self, report_type):
            """Generate the report and open it in its own window."""
            if report_type == 'summary':
                content = self._get_alumni_summary_text()
            elif report_type == 'engagement':
                content = self._get_engagement_report_text()
            elif report_type == 'donation':
                content = self._get_donation_report_text()
            elif report_type == 'custom':
                content = self._build_custom_report_text()
            else:
                content = "Unknown report type."
            self._open_report_window(report_type, content)

        def _open_report_window(self, report_type, content):
            """Show a generated report in a new window with Save-as-TXT and
            Email-to-Admin actions wired to the email system."""
            win = tk.Toplevel(self.root)
            win.title(f"{str(report_type).title()} Report")
            win.geometry("820x620")
            out = ScrolledText(win, wrap=tk.WORD)
            out.pack(fill=tk.BOTH, expand=True, padx=10, pady=10)
            out.insert(tk.END, content)

            btns = ttk.Frame(win)
            btns.pack(fill=tk.X, padx=10, pady=(0, 10))
            ttk.Button(btns, text="💾 Save as TXT",
                       command=lambda: self._save_report_as_txt(out)).pack(side=tk.LEFT, padx=(0, 10))
            ttk.Button(btns, text="✉ Email to Admin",
                       command=lambda: self._email_report_to_admin(out)).pack(side=tk.LEFT, padx=(0, 10))
            ttk.Button(btns, text="Close", command=win.destroy).pack(side=tk.RIGHT)

            # Mirror into the inline panel too, if the reports view built one.
            try:
                self.report_output.delete(1.0, tk.END)
                self.report_output.insert(tk.END, content)
            except (AttributeError, tk.TclError):
                pass

